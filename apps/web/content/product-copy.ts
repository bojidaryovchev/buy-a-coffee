/**
 * Our own product copy.
 *
 * Every entry here replaces the description the crawler observed. The reason is
 * search, not style: this shop and the source sell the same catalogue, so
 * publishing the source's product text would put the same paragraphs on two
 * domains. `descriptionText` feeds the visible lead paragraph, the meta
 * description and the Product JSON-LD at once, which are exactly the fields a
 * search engine compares — so duplicating it is the expensive kind of
 * duplication, and both sites lose.
 *
 * The rules this copy was written under:
 *
 *  - Every factual claim traces back to something the source published or to a
 *    normalised attribute we hold (blend ratio, origin, decaf, intensity,
 *    strength, pack size). Nothing about a coffee is invented, because a
 *    rewrite that invents facts is worse than the duplicate it replaced.
 *  - No sentence is a re-ordering of a source sentence. Same meaning, our
 *    words, our structure.
 *  - Products that share a source description because they are the same coffee
 *    in a different pack size get *different* text here. Copying our own
 *    paragraph across two of our own URLs would simply move the duplicate
 *    problem in-house.
 *
 * Keyed by `products.sourceKey`, which is the sync's identity for a product
 * and stable across runs — unlike `slug`, which is allocated once at first
 * sight and cannot be derived here.
 *
 * Applied to the database by `pnpm --filter @catalog/web copy:apply`, which
 * writes the override columns only. See `apply-product-copy.ts`.
 */

export interface ProductCopy {
  /**
   * One sentence. Becomes `description_text_override`, and through it the lead
   * paragraph, the meta description and the JSON-LD `description`.
   *
   * Kept under 200 characters so a search result shows the whole thing rather
   * than a cut-off clause.
   */
  readonly summary: string;
  /**
   * Body paragraphs, plain text. Become `description_html_override` as `<p>`
   * elements — the "За това кафе" section on the product page.
   */
  readonly body: readonly string[];
}

