/**
 * Regenerates `test/helpers/schema-vocabulary.ts`: the schema.org properties
 * each type this storefront emits may carry, so the structured-data checks can
 * run offline (`test/helpers/structured-data.ts`).
 *
 *   pnpm tsx scripts/schema-vocabulary.ts
 *
 * Reads the published vocabulary once (one GET to schema.org) and writes the
 * table for the types listed below — their own properties and every
 * supertype's. Add a type here when a builder starts emitting it.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

const TYPES = [
  "Article",
  "Brand",
  "BreadcrumbList",
  "ContactPoint",
  "DefinedRegion",
  "EntryPoint",
  "ImageObject",
  "ItemList",
  "ListItem",
  "MerchantReturnPolicy",
  "MonetaryAmount",
  "Offer",
  "OfferShippingDetails",
  "OpeningHoursSpecification",
  "Organization",
  "PostalAddress",
  "Product",
  "QuantitativeValue",
  "SearchAction",
  "ShippingDeliveryTime",
  "WebPage",
  "WebSite",
] as const;

const SOURCE = "https://schema.org/version/latest/schemaorg-current-https.jsonld";

interface Node {
  "@id": string;
  "@type": string | string[];
  "rdfs:subClassOf"?: { "@id": string } | Array<{ "@id": string }>;
  "schema:domainIncludes"?: { "@id": string } | Array<{ "@id": string }>;
  "schema:supersededBy"?: unknown;
}

const list = <T>(value: T | T[] | undefined): T[] =>
  value === undefined ? [] : Array.isArray(value) ? value : [value];
const local = (id: string) => id.replace(/^schema:/, "");

const vocabulary = (await (await fetch(SOURCE)).json()) as { "@graph": Node[] };
const graph = vocabulary["@graph"];
const parents = new Map<string, string[]>();
const propertiesOf = new Map<string, Set<string>>();

for (const node of graph) {
  const types = list(node["@type"]);
  if (types.includes("rdfs:Class")) {
    parents.set(
      local(node["@id"]),
      list(node["rdfs:subClassOf"]).map((parent) => local(parent["@id"])),
    );
  }
  if (types.includes("rdf:Property") && !node["schema:supersededBy"]) {
    for (const domain of list(node["schema:domainIncludes"])) {
      const type = local(domain["@id"]);
      if (!propertiesOf.has(type)) propertiesOf.set(type, new Set());
      propertiesOf.get(type)!.add(local(node["@id"]));
    }
  }
}

function ancestry(type: string, seen = new Set<string>()): Set<string> {
  if (seen.has(type)) return seen;
  seen.add(type);
  for (const parent of parents.get(type) ?? []) ancestry(parent, seen);
  return seen;
}

const table: Record<string, string[]> = {};
for (const type of TYPES) {
  if (!parents.has(type)) throw new Error(`schema.org has no type ${type}`);
  const allowed = new Set<string>();
  for (const ancestor of ancestry(type)) {
    for (const property of propertiesOf.get(ancestor) ?? []) allowed.add(property);
  }
  table[type] = [...allowed].sort();
}

const out = path.resolve(import.meta.dirname, "../test/helpers/schema-vocabulary.ts");
writeFileSync(
  out,
  `/* Generated by scripts/schema-vocabulary.ts from ${SOURCE}
   on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand. */

/** Every property schema.org allows on each type the storefront emits. */
export const SCHEMA_PROPERTIES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(table, null, 2)};
`,
);
console.log(`wrote ${out}: ${TYPES.length} types`);
