-- Every enquiry stored before the cart becomes one line, from the columns it
-- has: the product, its supplier's name, its slug and the quantity. No price
-- and no display name, because neither was recorded then; the panel says so
-- rather than guessing. An enquiry that already has lines is skipped, which is
-- what makes this safe to run twice, and what keeps it from touching anything
-- the new code wrote.
INSERT INTO "order_inquiry_items" ("inquiry_id", "position", "product_id", "product_name", "product_slug", "quantity", "created_at")
SELECT o."id", 0, o."product_id", o."product_name", o."product_slug", o."quantity", o."created_at"
FROM "order_inquiries" o
WHERE (o."product_id" IS NOT NULL OR o."product_name" IS NOT NULL OR o."product_slug" IS NOT NULL)
	AND NOT EXISTS (SELECT 1 FROM "order_inquiry_items" i WHERE i."inquiry_id" = o."id");
