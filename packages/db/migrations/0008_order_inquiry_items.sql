-- The cart: an order enquiry asks for several products, so what it asks for
-- moves into a table of its own, one row per product.
--
-- Both order forms write here — the cart, and the quick order on a product
-- page, which writes its one product as one row — so the panel and the mail
-- read a single shape. `order_inquiries` keeps its product columns: a quick
-- order still fills them, and the rows stored before this migration have
-- nothing else.
--
-- Additive, and safe to run twice. Nothing is dropped, renamed or retyped, so
-- the running storefront is unaffected when this is applied ahead of the code
-- that uses it. It must be applied ahead of that code: without this table a
-- cart order cannot be stored.
--
-- Generated by `pnpm db:generate` and cut down by hand. The generator diffed
-- against the 0004 snapshot, because 0005 to 0007 were written by hand and
-- left none, and so it also emitted every column those three already add —
-- statements that would fail on any database that ran them. They are left out
-- here; the 0008 snapshot beside this file is the generator's own and describes
-- the whole schema, so the next `db:generate` diffs from the truth again.

