-- Newsletters sent from the admin panel, and a row for every copy of each.
--
-- `newsletter_campaigns` is the message: subject, preheader, the body as the
-- owner typed it, the files it links to, and where the send has got to.
-- `newsletter_deliveries` is the recipient list, fixed when sending starts,
-- with one row per subscriber saying whether their copy went. That row is what
-- makes an interrupted send safe to resume: whoever already has an answer is
-- never sent another copy (`lib/newsletter/send.ts`).
--
-- Additive, and safe to run twice. Nothing existing is altered; the only link
-- to an existing table is a foreign key to `newsletter_subscribers` that sets
-- itself null if a subscriber row is ever removed. Apply it ahead of the code
-- that uses it: without these tables the panel's newsletter screen fails, and
-- nothing else does.
--
-- Generated by `pnpm db:generate` against the schema as committed, and made
-- re-runnable by hand. The 0009 snapshot beside this file is the generator's
-- own, so the next `db:generate` diffs from the truth.

